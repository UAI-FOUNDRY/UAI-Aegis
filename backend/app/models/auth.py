"""Login sessions, student devices and approved desktop-app builds."""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import Enum, ForeignKey, LargeBinary, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from .base import Base, CreatedMixin, IdMixin, UTCDateTime


class ClientKind(StrEnum):
    portal = "portal"
    desktop = "desktop"


class AuthSession(IdMixin, CreatedMixin, Base):
    """A signed-in session. Only the SHA-256 of the bearer token is stored, so a
    database leak does not leak usable tokens."""

    __tablename__ = "auth_sessions"

    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    token_hash: Mapped[bytes] = mapped_column(LargeBinary(32), unique=True)
    client: Mapped[ClientKind] = mapped_column(Enum(ClientKind, native_enum=False, length=16))
    expires_at: Mapped[datetime] = mapped_column(UTCDateTime())
    last_used_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    revoked_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    ip: Mapped[str | None] = mapped_column(String(64))
    user_agent: Mapped[str | None] = mapped_column(String(256))


class Device(IdMixin, CreatedMixin, Base):
    """A student's laptop, identified by an Ed25519 public key generated by the app.

    The private key never leaves the laptop. Every exam request is signed with it,
    so a copied login token is useless on another machine.
    """

    __tablename__ = "devices"

    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    public_key: Mapped[bytes] = mapped_column(LargeBinary(32), unique=True)
    label: Mapped[str] = mapped_column(String(120))
    platform: Mapped[str] = mapped_column(String(16))  # windows | macos | linux
    last_seen_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    revoked_at: Mapped[datetime | None] = mapped_column(UTCDateTime())


class ClientRelease(IdMixin, CreatedMixin, Base):
    """An approved build of the student app. With AEGIS_REQUIRE_KNOWN_CLIENT=true,
    exams can only be started from a version/build listed here as allowed."""

    __tablename__ = "client_releases"
    __table_args__ = (UniqueConstraint("platform", "version", "build_sha256"),)

    version: Mapped[str] = mapped_column(String(32))
    platform: Mapped[str] = mapped_column(String(16))
    build_sha256: Mapped[str] = mapped_column(String(64))
    status: Mapped[str] = mapped_column(String(16), default="allowed")  # allowed | revoked
    notes: Mapped[str | None] = mapped_column(String(500))
